"""Strict external-evidence attestation for still-generic maturity proof routes.

This module fills an infrastructure gap only: the proof policy already defines
capability-specific external acceptance routes, but many of those routes had no
repo-backed validator that could safely consume a real external observation.

Security / honesty boundaries:
- Only generic external routes generated by the committed policy are accepted.
  Specialized routes (for example sim-to-reality or post-deployment) are NOT
  accepted here and must keep using their dedicated semantic attestors.
- The exact capability, proof kind, subject, verifier and reference namespace are
  derived from the committed effective policy for the clean Git revision.
- External evidence must carry a separate verifier-key HMAC signature. The
  verifier key is never stored in the repository, receipt or proof ledger.
- The proof-ledger integrity key is a different trust root and is also external.
- Proof-kind-specific schemas are recomputed/validated; a generic ``passed=true``
  blob is never enough.
- This code never auto-generates evidence, never calls hardware/live systems and
  never says the underlying scientific claim is true. It only records a signed,
  bounded external observation when a trusted verifier actually supplies one.
"""
